'use strict';
const assert=require('node:assert/strict');
const {windowsFromVisibleText,planTierFromVisibleText}=require('../electron/usageWindows.cjs');
const now=Date.parse('2026-11-12T13:05:00+08:00');
const zh='套餐限额\nCodex、Work、工作空间智能体和 ChatGPT for Excel 共享使用额度。\n5 小时限额\n3小时34分钟 后重置\n剩余 0%\n每周限额\n6天22小时 后重置\n剩余 84%';
const result=windowsFromVisibleText(zh,now);
assert.equal(result.length,2,JSON.stringify(result));
assert.deepEqual(result.map(x=>x.id),['five-hour','weekly']);
assert.deepEqual(result.map(x=>x.remainingPercent),[0,84]);
assert.equal(Date.parse(result[0].resetAt)-now,214*60000);
assert.equal(Date.parse(result[1].resetAt)-now,(6*24+22)*3600000);
assert(result.every(x=>x.resetBasis==='countdown'));
assert.equal(windowsFromVisibleText('本周余额 84%\n重置 6天',now).length,0,'No window identity: do not guess');
const shorter=windowsFromVisibleText('5 小时限额\n2小时45分 后重置\n剩余 0%',now);
assert.equal(shorter.length,1);
assert.equal(Date.parse(shorter[0].resetAt)-now,165*60000,'Minutes abbreviated as 分 are recognized');
assert.equal(windowsFromVisibleText('5 小时限额\n剩余 0%\n每周限额\n剩余 84%',now)[0].resetAt,null);
assert.equal(windowsFromVisibleText('5 小时限额\nAPI Key sk-secret\n3小时34分钟后重置\n剩余0%',now)[0].remainingPercent,0,'Secret filtered');
assert.equal(planTierFromVisibleText('当前套餐\nPlus\n升级 Pro 200'), 'Plus');
assert.equal(planTierFromVisibleText('Your plan: Pro 100'), 'Pro 100');
assert.equal(planTierFromVisibleText('Current plan\nPro 200'), 'Pro 200');
assert.equal(planTierFromVisibleText('Current plan\n5x Pro'), 'Pro 5x');
assert.equal(planTierFromVisibleText('Current plan\n10x Pro'), 'Pro 10x');
assert.equal(planTierFromVisibleText('My plan: Pro 500'), 'Pro 500');
assert.equal(planTierFromVisibleText('你的套餐\nPro 5x'),null,'Unknown label alone not a tier claim');
assert.equal(planTierFromVisibleText('套餐限额\n升级套餐 Pro 200'),null,'Upsell is not current membership');
assert.equal(planTierFromVisibleText('Pricing\nPro 500\nPlus'),null,'Pricing options are not an account tier');
