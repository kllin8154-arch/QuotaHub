'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const ts=require('typescript')
const path=require('node:path')
const root=path.join(__dirname,'..')
const source=p=>fs.readFileSync(path.join(root,p),'utf8')
const out={}
vm.runInNewContext(ts.transpileModule(source('src/serviceTypes.ts'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:out})
assert.equal(out.serviceTypeOptions.length,7)
assert.equal(new Set(Array.from(out.serviceTypeOptions,x=>x.value)).size,7)
for(const x of ['api','subscription','hybrid','gateway','agent','local','other'])assert(out.isServiceType(x))
assert(!out.isServiceType('owner-token'))
assert.equal(out.defaultServiceType('relay','API'),'gateway')
assert.equal(out.defaultServiceType('chatgpt','订阅'),'subscription')
assert.equal(out.defaultServiceType('deepseek','API'),'api')
assert.equal(out.defaultServiceType('custom','API'),'other')
assert.equal(out.serviceTypeLabel('agent'),'AI 智能体 / IDE')
const app=source('src/App.tsx')
assert(app.includes("serviceType:draft.serviceType"),'new service type persists locally')
assert(app.includes("serviceType:isServiceType(p.serviceType)?p.serviceType:"),'old providers have safe metadata fallback')
assert(app.includes("category:value==='api'?'API':value==='subscription'?'订阅':p.category"),'agent metadata never overwrites existing billing category')
assert(app.includes("className=\"quota-alert-threshold\""))
assert(app.includes('modal-save'))
const css=source('src/ui-polish.css')
for(const x of ['.library-agent-main','.modal-footer .modal-cancel','.modal-footer .modal-save','.settings-card','.history-card','.insight-note','.library-search','.quota-alert-threshold','tone-clear','tone-warm']){
 assert(css.includes(x),'missing '+x)
}
assert(source('src/main.tsx').includes("import './ui-polish.css'"))
assert(source('src/HistoryChart.tsx').includes('var(--ui-chart-line'),'trends need theme-aware stroke color')
console.log('SERVICE_TYPES_MODAL_LIBRARY_SETTINGS_THEME_CONSISTENCY_PASS')
