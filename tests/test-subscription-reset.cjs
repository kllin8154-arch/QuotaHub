'use strict';
const assert=require('node:assert/strict');
const {visibleQuotaReset}=require('../electron/quotaReset.cjs');
const now=new Date('2026-11-12T09:00:00+08:00').getTime();
const expected=(s)=>new Date(s).getTime();
let r=visibleQuotaReset('本周已使用\n35%\n额度恢复时间 2026年11月13日 19:30',now);
assert(r && r.resetBasis==='explicit' && r.resetPrecision==='minute','Chinese date/time');
assert.equal(Date.parse(r.resetAt),new Date(2026,10,13,19,30).getTime());
r=visibleQuotaReset('Remaining 70%\nResets in 2 hours and 30 minutes',now);
assert.equal(Date.parse(r.resetAt)-now,150*60000);
assert.equal(r.resetBasis,'countdown');
r=visibleQuotaReset('Usage 80%\n重置时间：2026-11-13',now);
assert(r && r.resetPrecision==='date');
assert.equal(visibleQuotaReset('Usage 80%\nResets at 08:30 AM',now),null,'no date guessed from time-only');
assert.equal(visibleQuotaReset('Usage 80%\nResets in 2 hours\n限额恢复在 2026-11-14 16:00',now),null,'different quota windows are ambiguous');
assert.equal(visibleQuotaReset('Password x\nCookie session\nResets in 2 hours',now)?.resetBasis,'countdown','secret-free lines may still yield an independent reset');
assert.equal(visibleQuotaReset('Reset Token @example.com 2026-11-13 15:30',now),null,'secret-bearing lines excluded');
assert.equal(visibleQuotaReset('额度重置：2026-02-01 12:00',now),null,'past reset not presented');
assert.equal(visibleQuotaReset('额度重置：2026-12-20 12:00',now),null,'implausibly distant reset excluded');
assert.equal(visibleQuotaReset('额度重置：2026-11-31 12:00',now),null,'invalid calendar date excluded');
assert.equal(visibleQuotaReset('额度重置\n还有 1 天 3 小时',now)?.resetBasis,'countdown');
assert.equal(visibleQuotaReset('恭喜到账 100 元',now),null,'balance alone never implies a reset');
