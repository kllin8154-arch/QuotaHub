'use strict';
const assert=require('node:assert/strict');
const {createRetryGate}=require('../electron/retryGate.cjs');
let now=100000;
const gate=createRetryGate(()=>now);
assert.equal(gate.allowed('a'),true);
assert.equal(gate.failed('a',new Error('temporary network error')),90000);
assert.equal(gate.allowed('a'),false);
assert.equal(gate.allowed('b'),true,'failure of one account never blocks another');
now+=90000;
assert.equal(gate.allowed('a'),true);
assert.equal(gate.failed('a',new Error('network timeout')),180000);
now+=179999;
assert.equal(gate.allowed('a'),false);
now++;
assert.equal(gate.allowed('a'),true);
gate.succeeded('a');
assert.equal(gate.failed('a',new Error('temporary')),90000,'success resets exponential backoff');
assert.equal(gate.failed('limited',new Error('429 too many requests')),900000);
assert.equal(gate.failed('auth',new Error('401 login expired')),300000);
for(let i=0;i<8;i++)gate.failed('limit-max',new Error('429'));
now+=30*60_000;
assert.equal(gate.allowed('limit-max'),true,'backoff is capped');
gate.forget('a');
assert.equal(gate.allowed('a'),true);
console.log('RETRY_GATE_PER_ACCOUNT_BACKOFF_RESET_PASS');
