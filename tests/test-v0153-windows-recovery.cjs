'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {classifyWebError,officialFailureHtml,errorMessage,shouldHardRefresh,DEEPSEEK_RELOAD_INTERVAL_MS}=
 require('../electron/webWindowRecovery.cjs')
const {createRetryGate}=require('../electron/retryGate.cjs')
assert.equal(classifyWebError(429),'rate-limit')
assert.equal(classifyWebError(403),'access-denied')
assert.equal(classifyWebError(502),'server-error')
assert.equal(classifyWebError(0,-105),'network')
assert.equal(classifyWebError(200),'empty')
const html=officialFailureHtml('https://platform.deepseek.com/usage','rate-limit')
assert(html.includes('HTTP 429')&&html.includes('系统浏览器')&&html.includes('重试访问官网'))
assert(html.includes('上次有效记录')&&html.includes('data')===false)
assert(!html.includes('API Key')&&!html.includes('Cookie'))
assert.throws(()=>officialFailureHtml('https://platform.deepseek.com/usage" onclick="alert(1)','rate-limit'))
assert.throws(()=>officialFailureHtml('https://evil.example/usage','rate-limit'))
assert.equal(shouldHardRefresh('deepseek',1000,1000+DEEPSEEK_RELOAD_INTERVAL_MS-1),false)
assert.equal(shouldHardRefresh('deepseek',1000,1000+DEEPSEEK_RELOAD_INTERVAL_MS),true)
assert.equal(shouldHardRefresh('chatgpt',1000,1001),true)
let now=0
const gate=createRetryGate(()=>now)
gate.failed('deepseek',new Error('HTTP 429 Too Many Requests'))
assert(!gate.allowed('deepseek'),'Rate limit must block immediate retry')
assert(gate.allowed('chatgpt'),'Other quota providers stay independent')
now=15*60*1000-1;assert(!gate.allowed('deepseek'))
now++;assert(gate.allowed('deepseek'))
const main=fs.readFileSync(path.join(__dirname,'../electron/main.cjs'),'utf8')
const web=fs.readFileSync(path.join(__dirname,'../electron/webQuota.cjs'),'utf8')
assert(main.includes("pin:false,showTaskbar:false"))
assert(main.includes("skipTaskbar:true,alwaysOnTop"))
assert(main.includes("w.setSkipTaskbar(true)"))
assert(main.includes("result.showTaskbar=false"))
assert(!main.includes("label:'显示任务栏按钮'"),'Tray-only widget must not offer toggling back on')
assert(main.includes('document.querySelector("#root")'))
assert(main.includes('showDashboardFallback')&&main.includes('render-process-gone'))
assert(!main.includes("win.once('ready-to-show',()=>win.show())"),'Dashboard should not display before React mounts')
assert(web.includes("ses.webRequest?.onCompleted?.")&&web.includes("details.statusCode"))
assert(web.includes("if(health?.failure)")&&web.includes("recovery.failed(id,new Error('HTTP 429 Too Many Requests'))"))
assert(web.includes('shouldHardRefresh(binding.kind,health.lastReloadAt)'))
assert(!web.includes("try{win.webContents.reloadIgnoringCache()}catch{done()}"),'DeepSeek must not always reload ignoring cache')
assert(errorMessage('rate-limit').title==='官方服务暂时限流')
console.log('V0153_TRAY_ONLY_429_BACKOFF_WEB_FALLBACK_LOCAL_UI_WATCHDOG_PASS')
